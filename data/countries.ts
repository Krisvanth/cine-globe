export function getCountriesForLanguage(languageCode?: string): Country[] {
  if (!languageCode || languageCode.toLowerCase() === 'all') {
    return COUNTRIES;
  }
  const lang = languageCode.toLowerCase();
  const codes = LANGUAGE_TO_COUNTRIES[lang];
  if (codes && codes.length > 0) {
    const matched = COUNTRIES.filter((c) => codes.includes(c.code));
    if (matched.length > 0) return matched;
  }
  const directMatch = COUNTRIES.filter(
    (c) => c.primaryLanguage?.toLowerCase() === lang
  );
  return directMatch.length > 0 ? directMatch : COUNTRIES;
}
